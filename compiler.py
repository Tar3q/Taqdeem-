def get_eligible_tracks(category, college_name):
    c = college_name.lower()
    if category == 'طبية وصحية':
        return ['علمي أحياء']
    elif category == 'هندسية ومعمارية':
        return ['علمي هندسية']
    elif category == 'حاسوب وتقنية معلومات':
        return ['علمي هندسية', 'علمي أحياء']
    elif category == 'زراعية وبيطرية وبيئية':
        if 'هندسة زراعية' in c:
            return ['علمي هندسية', 'علمي أحياء']
        return ['علمي أحياء']
    elif category == 'علوم أساسية وتطبيقية':
        if any(k in c for k in ['رياضيات', 'فيزياء', 'إحصاء']):
            return ['علمي هندسية']
        elif any(k in c for k in ['أحياء', 'كيمياء', 'نبات', 'حيوان']):
            return ['علمي أحياء']
        return ['علمي أحياء', 'علمي هندسية']
    elif category == 'علوم تربوية':
        if any(k in c for k in ['علمي', 'أحياء', 'كيمياء', 'رياضيات', 'فيزياء']):
            return ['علمي أحياء', 'علمي هندسية']
        elif any(k in c for k in ['أدبي', 'لغة', 'تاريخ', 'جغرافيا', 'إسلامية']):
            return ['أدبي']
        return ['علمي أحياء', 'علمي هندسية', 'أدبي']
    return ['أدبي', 'علمي أحياء', 'علمي هندسية']

def detect_gender(college_name):
    c = college_name.lower()
    if 'طالبات' in c or 'بنات' in c or 'قبالة' in c:
        return 'طالبات فقط'
    elif 'طلاب فقط' in c or '(طلاب)' in c:
        return 'طلاب فقط'
    return 'مشترك'

